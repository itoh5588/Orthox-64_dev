/*
 * reboot(2) を叩くだけの道具。**`/reboot` として rootfs に置く。**
 *
 * ---- なぜ要るのか --------------------------------------------------------
 *
 * カーネルを差し替えるたびに人へ「電源を入れ直してください」と頼むのは
 * 遅い。これが在れば `/reboot` の一言で入れ替えられる (実測 21〜27 秒)。
 *
 * ---- なぜ毎回消えていたのか ----------------------------------------------
 *
 * **これまでリポジトリに無く、実機の gcc で毎回書き起こしていた。**
 * rootfs を焼き直すたびに消え、2026-08-29 と 2026-08-30 の 2 回踏んだ
 * (日報2026-08-29 の S-13)。**生成器に入れるのが正しい。**
 *
 * ---- ★ 静的リンクで置くこと ----------------------------------------------
 *
 * S-11 で `/lib/libc.so` を置いた結果、**実機の gcc の既定が動的リンクに
 * 変わった。**動的リンクで作ると PT_INTERP が付き、ローダが揃っていない
 * 状況では `not found` になる。**再起動の道具が起動しないのは最悪**なので、
 * ここだけは静的で置く。
 *
 * ---- 魔法の数 ------------------------------------------------------------
 *
 * Linux と同じで、**2 つ揃わないと効かない** (誤爆よけ)。
 * include/linux_syscalls.h の LINUX_REBOOT_* と対。
 */
#include <unistd.h>
#include <sys/syscall.h>

#define MAGIC1  0xfee1deadU
#define MAGIC2  672274793U      /* 0x28121969 */
#define CMD_RESTART 0x01234567U

static void put(const char *s) {
    const char *p = s;
    while (*p) p++;
    (void)write(1, s, (size_t)(p - s));
}

int main(void) {
    put("reboot: 機械をリセットする\n");
    syscall(SYS_reboot, (long)MAGIC1, (long)MAGIC2, (long)CMD_RESTART, 0L);
    /* **戻ってきたら失敗している。**黙って終わると「効かなかった」のか
     * 「効いたのに戻った」のか分からない */
    put("reboot: 戻ってきた。reboot(2) が効いていない\n");
    return 1;
}
