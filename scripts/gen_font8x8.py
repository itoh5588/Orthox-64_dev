# 表に無い文字はこれで出す (升目)。**空白で出さない** —
# 「字が無い」と「空白」は別で、混ぜると化けに気づけない
MISSING = "#######./##.....#/#.#.#.#./#..#..#./#.#.#.#./#.....#./#######./........"


def rows(art):
    r = art.split('/')
    assert len(r) == 8, f"8 行でない: {len(r)}"
    for x in r:
        assert len(x) == 8, f"8 列でない ({len(x)}): {x!r}"
    return r


def to_bytes(art):
    out = []
    for line in rows(art):
        v = 0
        for i, c in enumerate(line):
            if c == '#':
                v |= 0x80 >> i
        out.append(v)
    return out


def main():
    # 先に全部検算する。**1 文字でも寸法が違えば止める** —
    # 出力してからカーネルで気づくと、原因が字形なのか描画なのか分からない
    bad = []
    for ch, art in G.items():
        try:
            rows(art)
        except AssertionError as e:
            bad.append(f"{ch!r}: {e}")
    if bad:
        for b in bad:
            print("*** " + b, file=sys.stderr)
        sys.exit(1)

    w = sys.stdout.write
    w("/*\n")
    w(" * 8x8 の等幅ビットマップフォント (ASCII 0x20-0x7e)。\n")
    w(" *\n")
    w(" * **自動生成。手で直さないこと。** 字形は scripts/gen_font8x8.py にあり、\n")
    w(" *   python3 scripts/gen_font8x8.py > kernel/aarch64/font8x8.c\n")
    w(" * で作り直す。\n")
    w(" *\n")
    w(" * **字形はこのリポジトリで自分で描いたもの。** 既存のフォントデータを\n")
    w(" * 持ち込むとライセンスが絡む (本体は MIT)。\n")
    w(" *\n")
    w(" * 1 文字 8 バイト。1 行 1 バイトで、**bit7 が左端**。\n")
    w(" */\n")
    w("#include <stdint.h>\n\n")
    # **96 個。最後の 1 つは「表に無い文字」の升目。**
    # 95 個にして 0x7e に丸めると、日本語などが '~' として出て
    # 「化けている」ことに気づけない (実測でそうなった)
    w("#define AARCH64_FONT8X8_MISSING 95\n\n")
    w("const uint8_t aarch64_font8x8[96][8] = {\n")
    for code in range(0x20, 0x7f):
        ch = chr(code)
        art = G.get(ch, MISSING)
        b = to_bytes(art)
        name = ch if ch not in ('\\',) else '\\\\'
        w("    { " + ", ".join(f"0x{v:02x}" for v in b) + f" }},  /* 0x{code:02x} '{name}' */\n")
    w("    { " + ", ".join(f"0x{v:02x}" for v in to_bytes(MISSING)) + " },  /* 表に無い文字 */\n")
    w("};\n")


if __name__ == "__main__":
    main()
